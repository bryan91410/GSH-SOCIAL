-- Durcissement des contraintes (idempotent)
do $$
begin
  if not exists (
    select 1 from pg_constraint where conname = 'profiles_username_normalized'
  ) then
    alter table public.profiles
      add constraint profiles_username_normalized
      check (
        username = lower(username)
        and username ~ '^[a-z0-9_]{2,20}$'
      );
  end if;
end
$$;

do $$
begin
  if not exists (
    select 1 from pg_constraint where conname = 'posts_content_max_length'
  ) then
    alter table public.posts
      add constraint posts_content_max_length
      check (content is null or char_length(content) <= 2000);
  end if;
end
$$;

do $$
begin
  if not exists (
    select 1 from pg_constraint where conname = 'posts_image_url_max_length'
  ) then
    alter table public.posts
      add constraint posts_image_url_max_length
      check (image_url is null or char_length(image_url) <= 2048);
  end if;
end
$$;

do $$
begin
  if not exists (
    select 1 from pg_constraint where conname = 'comments_content_max_length'
  ) then
    alter table public.comments
      add constraint comments_content_max_length
      check (char_length(content) <= 500);
  end if;
end
$$;

do $$
begin
  if not exists (
    select 1 from pg_constraint where conname = 'messages_content_max_length'
  ) then
    alter table public.messages
      add constraint messages_content_max_length
      check (char_length(content) <= 2000);
  end if;
end
$$;

